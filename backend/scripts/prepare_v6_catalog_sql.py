"""Reproduce the inactive SQL catalog from hash-pinned sources; never execute SQL."""

import argparse
import json
from dataclasses import asdict
from hashlib import sha256
from pathlib import Path

from app.modules.planning.service import PlanningService
from app.modules.planning.v6_service import private_json
from app.modules.workouts.joren_v6_official import official_catalog
from app.modules.workouts.joren_v6_phase import PHASE_SOURCES
from app.modules.workouts.v6_storage import canonical_document, catalog_document


def prepare() -> str:
    rows = []
    for t in official_catalog():
        document = catalog_document(t)
        source = t.source_revision
        spec = next(s for s in PHASE_SOURCES if s.sha256 == source.source_sha256)
        rows.append(
            {
                "template_id": str(t.id),
                "logical_key": str(t.template_key),
                "version": t.version,
                "discipline": t.discipline.value,
                "name": t.name,
                "description": t.description,
                "duration_minutes": str(t.duration_minutes)
                if t.duration_minutes is not None
                else None,
                "distance_meters": t.distance_meters,
                "intensity_bucket": t.intensity_bucket.value,
                "expected_rpe_min": t.expected_rpe_min,
                "expected_rpe_max": t.expected_rpe_max,
                "fallback_compatibility": t.fallback_compatibility.value,
                "source_sha256": source.source_sha256,
                "worksheet": spec.sheet_name,
                "source_row": source.source_row,
                "planned_method": t.official.method,
                "reference_version": t.official.parameters,
                "official_decimal": str(t.official.value),
                "numerator": str(t.official.numerator),
                "denominator": str(t.official.denominator),
                "source_snapshot": json.loads(private_json(asdict(t))),
                "document": document,
                "public_snapshot": PlanningService._deck_item(t).model_dump(
                    mode="json"
                ),
                "document_sha256": sha256(
                    canonical_document(document).encode()
                ).hexdigest(),
            }
        )
    data = json.dumps(rows, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return (
        """-- GENERATED by backend/scripts/prepare_v6_catalog_sql.py; INACTIVE ONLY.
-- No historical load, occurrence, activation or retirement is changed.
create temporary table v6_import on commit drop as
select * from jsonb_to_recordset($v6_catalog$"""
        + data
        + """$v6_catalog$::jsonb) as r(
  template_id uuid, logical_key uuid, version integer, discipline text, name text,
  description text, duration_minutes numeric, distance_meters integer,
  intensity_bucket text,
  expected_rpe_min smallint, expected_rpe_max smallint, fallback_compatibility text,
  source_sha256 text, worksheet text, source_row integer, planned_method text,
  reference_version text, official_decimal text, numerator text, denominator text,
  source_snapshot jsonb, document jsonb, public_snapshot jsonb, document_sha256 text
);
insert into public.workout_templates(id, template_key, version, discipline,
  name, description, duration_minutes, distance_meters, intensity_bucket,
  expected_rpe_min, expected_rpe_max,
  fallback_compatibility, inactive_v6)
select template_id, logical_key, version, discipline, name, description,
  duration_minutes, distance_meters, intensity_bucket, expected_rpe_min,
  expected_rpe_max, fallback_compatibility, true from v6_import;
insert into private.v6_source_revisions(template_id, logical_key, source_sha256,
  worksheet, source_row, planned_method, reference_version, official_decimal,
  planned_tss, numerator, denominator,
  source_snapshot, document, public_snapshot)
select template_id, logical_key, source_sha256, worksheet, source_row,
  planned_method, reference_version, official_decimal, official_decimal::numeric,
  numerator, denominator, source_snapshot, document, public_snapshot from v6_import;
do $$ begin
  if (select count(*) from private.v6_source_revisions) <> 77 then
    raise exception 'V6 source coverage mismatch';
  end if;
end; $$;
"""
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    content = prepare()
    if args.output.exists() and args.output.read_text(encoding="utf-8") != content:
        raise SystemExit("Conflicting immutable catalog output; use a new review path.")
    args.output.write_text(content, encoding="utf-8", newline="\n")
    print("Prepared 77 inactive source revisions; no database connection.")


if __name__ == "__main__":
    main()
